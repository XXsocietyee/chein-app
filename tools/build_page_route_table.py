#!/usr/bin/env python3
"""Generate Core/MiniProgramPages.swift: every mini-program page path the native app knows about.

Sources: the `"pages/..."` / `"subpackage*/..."` literals in Core/ and App/ (excluding the generated file) plus
docs/parity/page-map.csv. `--check` fails when the committed file differs from a fresh generation, which is the
drift gate wired into tools/check_scaffold.py. Typed routes are declared in TYPED below; every other page maps to
`AppRoute.unsupported(path)`.
"""
import csv, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'Core/MiniProgramPages.swift'
LITERAL = re.compile(r'"(/?(?:pages|subpackage[A-Za-z0-9]*)/[^"\n]*)"')
PATH = re.compile(r'^(?:pages|subpackage[A-Za-z0-9]*)(?:/[A-Za-z0-9_-]+)+$')

# page -> (AppRoute case, id-carrying). Keep in step with NativeContentTarget.Kind.sourcePath.
TYPED = {
    'pages/activity/detail/index': 'activity',
    'pages/club/detail/index': 'club',
    'pages/topic/index/index': 'topic',
    'pages/templatedetail/templatedetail': 'template',
    'pages/square/detail/index': 'post',
    'subpackageRoam/poi-detail/index': 'poi',
    'subpackageRoam/session/index': 'roamSession',
}

def normalize(raw):
    path = raw.split('?', 1)[0].lstrip('/')
    return path if PATH.match(path) else None

def scan_literals():
    found = set()
    for base in ('Core', 'App'):
        for f in sorted((ROOT / base).rglob('*.swift')):
            if f == OUT:
                continue
            for m in LITERAL.finditer(f.read_text(encoding='utf-8')):
                p = normalize(m.group(1))
                if p:
                    found.add(p)
    return found

def csv_pages():
    with open(ROOT / 'docs/parity/page-map.csv', encoding='utf-8', newline='') as fh:
        return {p for p in (normalize(r['mini_path']) for r in csv.DictReader(fh)) if p}

def case_name(path):
    parts = [p for p in re.split(r'[/_-]', path) if p]
    if parts[0] == 'pages':
        parts = parts[1:]
    name = parts[0].lower() + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    return name

def generate():
    pages = sorted(scan_literals() | csv_pages())
    for t in TYPED:
        assert t in pages, f'typed page missing from table: {t}'
    names = {}
    for p in pages:
        n = case_name(p)
        assert n not in names, f'case name collision: {p} vs {names[n]}'
        names[n] = p
    out = ['// GENERATED by tools/build_page_route_table.py. Do not edit; run the script.',
           '// Sources: "pages/..." literals in Core/ + App/, and docs/parity/page-map.csv.', '',
           '/// Every mini-program page path the native app references. Parse-only; presenting a page is the host\'s decision.',
           'public enum MiniProgramPage: String, CaseIterable, Hashable, Sendable {']
    out += [f'    case {n} = "{names[n]}"' for n in sorted(names, key=lambda k: names[k])]
    out += ['',
            '    /// Accepts a leading slash and ignores any query; anything not in the table is nil. Lane G: a merchant-center,',
            '    /// merchant-onboarding or coop page is nil while `PlayerLaunch.merchantCenterEnabled` is false (Release).',
            '    public init?(path: String) {',
            '        let bare = path.split(separator: "?", maxSplits: 1, omittingEmptySubsequences: false).first.map(String.init) ?? path',
            '        guard !PlayerLaunch.isHidden(page: bare) else { return nil }',
            '        self.init(rawValue: bare.hasPrefix("/") ? String(bare.dropFirst()) : bare)',
            '    }',
            '',
            '    /// Lane G: true for a merchant-center, merchant-onboarding or coop page (hidden in the player Release build).',
            '    public var isMerchantCenterPage: Bool { PlayerLaunch.isMerchantCenterPage(rawValue) }',
            '',
            '    /// The typed route for this page and its single positive `id`; every other page (or a bad id) is `.unsupported`.',
            '    public func route(id: Int?) -> AppRoute {',
            '        switch self {']
    for p in sorted(TYPED):
        k = TYPED[p]
        out += [f'        case .{case_name(p)}:', f'            return id.flatMap(AppRoute.{k}ID) ?? .unsupported(rawValue)']
    out += ['        default:', '            return .unsupported(rawValue)', '        }', '    }', '}', '']
    return '\n'.join(out)

def main():
    text = generate()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            raise SystemExit('Core/MiniProgramPages.swift is stale; run python3 tools/build_page_route_table.py')
        print(f'PASS page route table: {text.count(chr(10) + "    case ")} pages')
    else:
        OUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUT.relative_to(ROOT)}')

main()
