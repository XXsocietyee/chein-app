import Foundation

/// Wire descriptors intentionally contain no host, credentials or network implementation.
public struct TemplateAuthoringRequest: Equatable, Codable {
    public enum Body: Equatable, Codable { case form([String: String]), json([String: TemplateAuthoringJSON]) }
    public let path: String
    public let method: String
    public let body: Body
    public let mutates: Bool
    public init(path: String, body: Body, mutates: Bool) { self.path = path; method = "POST"; self.body = body; self.mutates = mutates }
}
public enum TemplateAuthoringIntent: String, Codable, CaseIterable { case saveDraft, publish }
public enum TemplateAuthoringContract {
    public static func listMine(scope: String? = nil) -> TemplateAuthoringRequest {
        .init(path: "/api/template/my-list", body: .form(shelfFields([
            "is_quote": "", "keyword": "", "category_id": "", "pageNum": "1", "pageSize": "100"
        ], scope: scope)), mutates: false)
    }
    /// Merchant `mytemplate` sends `scope=MERCHANT`. A player omits the field.
    static func shelfFields(_ fields: [String: String], scope: String?) -> [String: String] {
        guard scope == "MERCHANT" else { return fields }
        var copy = fields
        copy["scope"] = "MERCHANT"
        return copy
    }
    /// Backend `ApiTemplateController#updateLibraryStatus` reads `status` (1 上架, 2 撤回待审, 3 下架); a
    /// `publish_status` field is ignored and the call fails with 发布状态参数错误 (PLY-26-1).
    public static func libraryStatus(id: AuthoringPlayTemplateID, current: Int?, scope: String? = nil) -> TemplateAuthoringRequest {
        marketStatus(id: id, target: current == 1 ? 3 : 1, scope: scope)!
    }
    /// Mini-program `utils/template-market.js` `_marketStatusTarget`: 1 上架广场, 2 撤回广场审核, 3 从广场下架.
    public static func marketStatus(id: AuthoringPlayTemplateID, target: Int, scope: String? = nil) -> TemplateAuthoringRequest? {
        guard [1, 2, 3].contains(target) else { return nil }
        return .init(path: "/api/template/updateLibraryStatus", body: .form(shelfFields([
            "template_id": String(id.rawValue), "status": String(target)
        ], scope: scope)), mutates: true)
    }
    /// 提交广场审核: `POST /api/template/{memberTemplateId}/market-submit` (`@RequestParam scope` optional, omitted for a player).
    public static func marketSubmit(id: AuthoringPlayTemplateID, scope: String? = nil) -> TemplateAuthoringRequest {
        .init(path: "/api/template/\(id.rawValue)/market-submit", body: .form(shelfFields([:], scope: scope)), mutates: true)
    }
    /// Exact `/api/template/{positive id}/market-submit` shape, as `marketSubmit(id:)` builds it.
    public static func isMarketSubmitPath(_ path: String) -> Bool {
        path.range(of: "^/api/template/[1-9][0-9]{0,17}/market-submit$", options: .regularExpression) != nil
    }
    public static func remove(id: AuthoringPlayTemplateID, scope: String? = nil) -> TemplateAuthoringRequest {
        .init(path: "/api/template/delete", body: .form(shelfFields(["template_id": String(id.rawValue)], scope: scope)), mutates: true)
    }
    public static func dictionary(_ type: String) throws -> TemplateAuthoringRequest {
        guard ["app_template_difficulty", "app_template_duration", "app_template_players"].contains(type) else { throw TemplateAuthoringError.invalidContract }
        return .init(path: "/api/common/dict", body: .form(["dictType": type]), mutates: false)
    }
    /// A local editor is not remote authorization. Reject even forged descriptors at every transport boundary.
    public static func permitsRemoteConfiguration(_ request: TemplateAuthoringRequest) -> Bool {
        let privateConfiguration: Set<String> = ["preferenceJson", "sensorType", "sensorConfig", "sensorChallengeType", "sensorConfigJson"]
        switch request.body {
        case .json(let fields):
            guard privateConfiguration.isDisjoint(with: fields.keys),
                  ["/api/template/draft", "/api/template/publish"].contains(request.path) else { return false }
        case .form(let fields):
            // Existing shelf/dictionary forms never carry completion configurations.
            guard privateConfiguration.isDisjoint(with: fields.keys), fields["validationMethod"] == nil else { return false }
        }
        guard ["/api/template/draft", "/api/template/publish"].contains(request.path) else { return true }
        guard request.method == "POST", request.mutates, case .json(let fields) = request.body, fields["id"] == nil,
              let title = fields["title"]?.string, !title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              fields["description"]?.string != nil, fields["isSync"] != nil else { return false }
        if let scope = fields["scope"], scope != .string("MERCHANT") { return false }
        // Only fields generated by the existing 0...5 serializer are remote-writable.
        let stringFields: Set<String> = ["title", "description", "imgUrl", "players", "usageLocation", "requiredMaterials", "difficulty",
            "ruleInstructions", "activityCategoryids", "questionName", "questionImg", "questionAudio", "questionAnswer", "questionA",
            "questionB", "questionC", "questionD", "correctAnswer", "questionOptionMediaJson", "hint1", "hint2", "answerReveal",
            "photoRequireDesc", "advancedConfigJson", "feedbackText", "medalImg", "medalName", "medalStyle", "storyText", "storyImg", "storyJson", "audioUrl"]
        let numberFields: Set<String> = ["originalTemplateId", "categoryId", "duration", "isSync", "validationMethod", "photoReview", "couponId", "audioDuration"]
        let remoteKeys = Set(fields.keys).subtracting(["scope"])
        guard remoteKeys.isSubset(of: stringFields.union(numberFields)) else { return false }
        for (key, value) in fields where key != "scope" {
            if stringFields.contains(key) { guard value.string != nil else { return false } }
            else { guard case .number(let number) = value, number.isFinite, number.rounded() == number else { return false } }
        }
        if let rawMethod = fields["validationMethod"] {
            guard case .number(let method) = rawMethod, method.isFinite, method.rounded() == method,
                  (0...5).contains(method) else { return false }
        } else {
            // Absent method is solely the existing finish-disabled shape, not an alternate authoring dispatch.
            let completionFields: Set<String> = ["questionName", "questionImg", "questionAudio", "questionAnswer", "questionA", "questionB", "questionC", "questionD",
                "correctAnswer", "questionOptionMediaJson", "hint1", "hint2", "answerReveal", "photoRequireDesc", "photoReview", "advancedConfigJson"]
            guard completionFields.isDisjoint(with: fields.keys) else { return false }
        }
        return true
    }
    public static func request(_ draft: TemplateAuthoringDraft, intent: TemplateAuthoringIntent) throws -> TemplateAuthoringRequest {
        guard !draft.validationMethod.isLocalConfigurationOnly, draft.canSave, intent != .publish || draft.publishIssues.isEmpty else { throw TemplateAuthoringError.invalidDraft }
        return .init(path: intent == .saveDraft ? "/api/template/draft" : "/api/template/publish", body: .json(try payload(draft)), mutates: true)
    }
    public static func payload(_ d: TemplateAuthoringDraft) throws -> [String: TemplateAuthoringJSON] {
        guard !d.validationMethod.isLocalConfigurationOnly else { throw TemplateAuthoringError.unavailable }
        var p: [String: TemplateAuthoringJSON] = ["title": .string(d.title.trimmingCharacters(in: .whitespacesAndNewlines)), "description": .string(d.description.trimmingCharacters(in: .whitespacesAndNewlines)), "isSync": .number(Double(d.isSync))]
        func string(_ name: String, _ value: String?) { if let value { p[name] = .string(value) } }
        func number(_ name: String, _ value: Int?) { if let value { p[name] = .number(Double(value)) } }
        number("id", d.id?.rawValue); number("originalTemplateId", d.originalTemplateID?.rawValue)
        number("categoryId", d.categoryId); number("duration", d.duration)
        string("imgUrl", d.imgUrl); string("players", d.players); string("usageLocation", d.usageLocation)
        string("requiredMaterials", d.requiredMaterials); string("difficulty", d.difficulty)
        string("ruleInstructions", d.ruleInstructions); string("activityCategoryids", d.activityCategoryids)
        if d.finishEnabled {
            p["validationMethod"] = .number(Double(d.validationMethod.rawValue))
            if d.validationMethod == .text || d.validationMethod == .choice {
                string("questionName", d.questionName); string("questionImg", d.questionImg); string("questionAudio", d.questionAudio)
            }
            if d.validationMethod == .text { string("questionAnswer", d.questionAnswer) }
            if d.validationMethod == .choice {
                string("questionA", d.questionA); string("questionB", d.questionB); string("questionC", d.questionC); string("questionD", d.questionD)
                string("correctAnswer", d.correctAnswer); string("questionOptionMediaJson", d.questionOptionMediaJson)
            }
            if d.validationMethod.supportsLegacyHints && d.legacyHintsAreEnabled { string("hint1", d.hint1); string("hint2", d.hint2); string("answerReveal", d.answerReveal) }
            if d.validationMethod == .photo { string("photoRequireDesc", d.photoRequireDesc); number("photoReview", d.photoReview) }
            let raw = try d.advanced.serialize(); if !raw.isEmpty { p["advancedConfigJson"] = .string(raw) }
        }
        if d.rewardEnabled { string("feedbackText", d.feedbackText); number("couponId", d.couponId); string("medalImg", d.medalImg); string("medalName", d.medalName)
            if !(d.medalName ?? "").isEmpty || !(d.medalImg ?? "").isEmpty { string("medalStyle", d.medalStyle) }
        }
        if d.storyEnabled { string("storyText", try d.preparedStoryText()); string("storyImg", d.storyImg); string("storyJson", d.storyJson) }
        if d.voiceEnabled { string("audioUrl", d.audioUrl); number("audioDuration", d.audioDuration) }
        if d.operationScope == "MERCHANT" { p["scope"] = .string("MERCHANT") }
        return p
    }
    /// Mini-program `from=citynode` posts the template body to this path, not `/api/template/publish`.
    public static let cityNodeSubmitPath = "/api/merchant/city-node/template/submit"
    /// `temp/index.js` `toNodeTemplate`: rename the few fields the node entity does not share.
    public static func cityNodeBody(_ payload: [String: TemplateAuthoringJSON], interactionType: String) -> [String: TemplateAuthoringJSON] {
        var body = payload
        if let method = body.removeValue(forKey: "feedbackMethod") { body["feedbackMethodStr"] = .string(method.string ?? "") }
        body["interactionType"] = .string(interactionType)
        if let categories = body.removeValue(forKey: "categoryIds")?.string {
            body["activityCategoryids"] = .string(categories)
            if let first = categories.split(separator: ",").first, let id = Int(first), id > 0 {
                body["categoryId"] = .number(Double(id))
            }
        }
        body.removeValue(forKey: "audioFileName")
        body.removeValue(forKey: "audioFormat")
        body.removeValue(forKey: "copyFromTemplateId")
        body.removeValue(forKey: "clearFields")
        body.removeValue(forKey: "scope")
        return body
    }
    public static func decodeList(_ data: Data, httpStatus: Int) throws -> [DiscoveryPlayTemplate] {
        try requireSuccess(data, httpStatus: httpStatus)
        let body = try JSONDecoder().decode([String: TemplateAuthoringJSON].self, from: data)
        guard let rows = body["data"]?.array ?? body["data"]?.object?["rows"]?.array else { throw TemplateAuthoringError.invalidContract }
        return try JSONDecoder().decode([DiscoveryPlayTemplate].self, from: JSONEncoder().encode(rows))
    }
    public static func requireSuccess(_ data: Data, httpStatus: Int) throws {
        if httpStatus == 401 { throw APIError.unauthorized }
        guard (200..<300).contains(httpStatus) else { throw APIError.httpStatus(httpStatus) }
        let body = try JSONDecoder().decode([String: TemplateAuthoringJSON].self, from: data)
        guard let code = body["code"]?.integer else { throw TemplateAuthoringError.invalidContract }
        if code == 401 { throw APIError.unauthorized }
        guard code == 200 else { throw TemplateAuthoringRejection(message: body["msg"]?.string ?? "", code: code) }
    }
}
public struct TemplateAuthoringRejection: Error, Equatable {
    public let message: String
    public let code: Int
    public var duplicateName: Bool { message.contains("已存在") }
    public var contentRejected: Bool { !message.contains("网络") && !message.contains("稍后重试") && ["违规", "敏感", "不合规", "含有"].contains(where: message.contains) }
    public var messageKey: String { duplicateName ? "templateAuthor.duplicateName" : contentRejected ? "templateAuthor.contentRejected" : "templateAuthor.rejected" }
}
public struct TemplateAuthoringDictionaryOption: Equatable, Identifiable {
    public let value: String
    public let label: String
    public var id: String { value }
    /// Source fallback values are index strings; display labels remain source data.
    public static func fallback(_ type: String) -> [Self] {
        let labels = ["app_template_difficulty": ["简易", "一般", "困难"], "app_template_duration": ["10min", "16min", "20min", "23min"], "app_template_players": ["1-2 人", "3-5 人", "6 人以上"]][type] ?? []
        return labels.enumerated().map { .init(value: String($0.offset), label: $0.element) }
    }
}
